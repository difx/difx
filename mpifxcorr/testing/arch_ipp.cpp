/* Only built when IPP is available (see Makefile).  IPP is taken as the
 * reference for what each routine should do. */

#include <string.h>
#include "arch_api.h"
#include "arch_ipp.h"		/* ../src/architecture.h.in with @ipp_enabled@ = 1 */

#if ARCH != INTEL
#error "arch_ipp.h does not select the Intel (IPP) architecture"
#endif

/* Routines whose vector* macro does not compile with IPP (generated by
 * find_skips.sh at build time) */
#include "arch_ipp_skips.h"

static ArchImpl ippImpl;
static ArchImplRegister registerImpl(ippImpl, "ipp", 99);

#define ARCH_RNDMODE(r)	((r) ? vecRndNear : vecRndZero)
#define ARCH_FFTFLAG(f)	((f) ? vecFFT_ReNorm : vecFFT_NoReNorm)

#define WRAP(name, params, call) \
	static int w_##name params { return (int)(call); } \
	static ArchRegister reg_##name(ippImpl, #name, (arch_fn)w_##name);
#define WRAP_BODY(name, params, ...) \
	static int w_##name params __VA_ARGS__ \
	static ArchRegister reg_##name(ippImpl, #name, (arch_fn)w_##name);
#define SKIP(name) \
	static ArchSkip skip_##name(ippImpl, #name, ARCH_SKIP_##name);

#include "arch_wrappers.inc"
