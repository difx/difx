"""Step 1: fresh checkout, clean build under an interceptor, compile_commands.json.

Layout below the work directory:
    src/                      fresh clone; built in-source by install-difx
    checkout.json             branch / sha of the clone
    install/                  DIFXROOT for the analysis build
    setup.bash                copy of the user's setup.bash with DIFXROOT redirected
    logs/build-<stamp>.log    full build output
    compdb/raw.json           database as produced by the interceptor
    compdb/coverage.json      per-component source vs compiled counts
    src/compile_commands.json filtered database (C/C++ only, existing files, one entry per file)
"""

import datetime
import json
import os
import re
import shlex
import shutil
import subprocess
import sys

from . import components

C_CXX_EXT = {".c", ".cc", ".cpp", ".cxx", ".c++", ".C"}


def log(msg):
    print(f"[compdb] {msg}", flush=True)


def find_tool(name, tool_bin):
    path = os.environ.get("PATH", "")
    if tool_bin:
        path = tool_bin + os.pathsep + path
    return shutil.which(name, path=path)


def git(*args, **kw):
    return subprocess.run(["git", *args], check=True, text=True,
                          stdout=subprocess.PIPE, **kw).stdout.strip()


def fresh_checkout(repo, ref, src):
    """Clone `repo` at `ref` into `src`; return a description of what was checked out."""
    branch = ref
    if os.path.isdir(repo):
        branch = git("-C", repo, "rev-parse", "--abbrev-ref", ref)
        ref = git("-C", repo, "rev-parse", "--verify", ref + "^{commit}")
    log(f"cloning {repo} @ {ref} -> {src}")
    shutil.rmtree(src, ignore_errors=True)
    git("clone", "--quiet", "--no-checkout", repo, src)
    git("-C", src, "checkout", "--quiet", "--detach", ref)
    return {
        "repo": repo,
        "branch": branch if branch != "HEAD" else "detached",
        "sha": git("-C", src, "rev-parse", "HEAD"),
        "commit_date": git("-C", src, "log", "-1", "--format=%cI"),
        "subject": git("-C", src, "log", "-1", "--format=%s"),
    }


def read_checkout(work):
    with open(os.path.join(work, "checkout.json")) as f:
        return json.load(f)


def write_setup(setup_script, dest, prefix):
    """Copy setup.bash, pointing DIFXROOT at the analysis install prefix."""
    with open(setup_script) as f:
        text = f.read()
    text, n = re.subn(r"^(\s*export\s+DIFXROOT=).*$", rf"\g<1>{prefix}", text,
                      flags=re.MULTILINE)
    if n == 0:
        raise RuntimeError(f"no 'export DIFXROOT=' line in {setup_script}")
    with open(dest, "w") as f:
        f.write(f"# Generated by the static-analysis suite from {setup_script}\n")
        f.write(text)


def choose_interceptor(build_cfg):
    want = build_cfg.get("compdb_tool", "auto")
    tool_bin = build_cfg.get("_tool_bin")
    for name in (["bear", "compiledb"] if want == "auto" else [want]):
        exe = find_tool(name, tool_bin)
        if exe:
            return name, exe
    raise RuntimeError(f"no compile-database tool found (wanted: {want})")


def run_build(cfg, comps, src, work, raw_db, logfile):
    prefix = os.path.join(work, "install")
    shutil.rmtree(prefix, ignore_errors=True)
    setup = os.path.join(work, "setup.bash")
    write_setup(cfg.path("setup_script"), setup, prefix)

    b = dict(cfg.build, _tool_bin=cfg.tool_bin)
    tool, exe = choose_interceptor(b)
    only = ",".join(c.name for c in comps if c.enabled)
    makeflags = f"-w V=1 -j{b.get('jobs', 1)}"
    install = ["python3", "-u", "./install-difx", "--doonly=" + only,
               "--makeflags=" + makeflags, *b.get("install_args", [])]
    script = (f"source {shlex.quote(setup)} && cd {shlex.quote(src)} && "
              + shlex.join(install))
    cmd = ["bash", "-c", script]
    if tool == "bear":
        cmd = [exe, "--output", raw_db, "--"] + cmd

    log(f"building with {tool}: {' '.join(install)}")
    log(f"build log: {logfile}")
    with open(logfile, "w") as f:
        status = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT).returncode
    if status:
        log(f"BUILD FAILED (exit {status}); database will cover only what was compiled")

    if tool == "compiledb":
        subprocess.run([exe, "--parse", logfile, "--output", raw_db, "--overwrite",
                        "--build-dir", src], check=True)
    return status


def filter_db(raw_db, out_db):
    """Keep C/C++ entries for existing files, one per file, with absolute paths."""
    with open(raw_db) as f:
        entries = json.load(f)
    seen = {}
    for e in entries:
        path = os.path.normpath(os.path.join(e["directory"], e["file"]))
        if os.path.splitext(path)[1] not in C_CXX_EXT or "conftest" in path:
            continue
        if not os.path.exists(path) or path in seen:
            continue
        seen[path] = dict(e, file=path)
    result = sorted(seen.values(), key=lambda e: e["file"])
    with open(out_db, "w") as f:
        json.dump(result, f, indent=1)
    return result


def coverage(comps, src, db):
    """Compare tracked C/C++ sources of each enabled component with the database."""
    compiled = {os.path.relpath(e["file"], src) for e in db}
    tracked = [p for p in git("-C", src, "ls-files").splitlines()
               if os.path.splitext(p)[1] in C_CXX_EXT]
    report, claimed = [], set()
    for c in comps:
        if not c.enabled:
            continue
        under = lambda p: p.startswith(c.path + "/")
        src_files = sorted(p for p in tracked if under(p))
        db_files = sorted(p for p in compiled if under(p))
        claimed.update(db_files)
        report.append({
            "component": c.name, "category": c.category, "path": c.path,
            "analysed": c.analysed, "excluded": c.excluded,
            "tracked_sources": len(src_files), "compiled": len(db_files),
            "generated": sorted(set(db_files) - set(src_files)),
            "not_compiled": sorted(set(src_files) - set(db_files)),
        })
    return report, sorted(compiled - claimed)


def print_coverage(report, unclaimed):
    print(f"\n{'component':16s} {'path':34s} {'tracked':>7s} {'compiled':>8s} {'missing':>7s}")
    for r in report:
        note = "" if r["analysed"] else f"  (excluded: {r['excluded']})"
        print(f"{r['component']:16s} {r['path']:34s} {r['tracked_sources']:7d} "
              f"{r['compiled']:8d} {len(r['not_compiled']):7d}{note}")
    if unclaimed:
        print(f"\n{len(unclaimed)} compiled files outside any component, e.g. {unclaimed[:5]}")


def run(cfg, checkout=True, build=True):
    work = cfg.workdir
    src = os.path.join(work, "src")
    dbdir = os.path.join(work, "compdb")
    logdir = os.path.join(work, "logs")
    os.makedirs(dbdir, exist_ok=True)
    os.makedirs(logdir, exist_ok=True)
    raw_db = os.path.join(dbdir, "raw.json")
    out_db = os.path.join(src, "compile_commands.json")

    comps = components.read_components(cfg.path("install_script"), cfg.excluded)
    status = 0
    if build:
        if checkout:
            info = fresh_checkout(cfg.source_repo, cfg.source_ref, src)
            with open(os.path.join(work, "checkout.json"), "w") as f:
                json.dump(info, f, indent=1)
            log(f"checked out {info['branch']} @ {info['sha']}")
        stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        status = run_build(cfg, comps, src, work, raw_db,
                           os.path.join(logdir, f"build-{stamp}.log"))

    db = filter_db(raw_db, out_db)
    log(f"{len(db)} translation units -> {out_db}")
    report, unclaimed = coverage(comps, src, db)
    with open(os.path.join(dbdir, "coverage.json"), "w") as f:
        json.dump({"components": report, "unclaimed": unclaimed}, f, indent=1)
    print_coverage(report, unclaimed)
    return status
