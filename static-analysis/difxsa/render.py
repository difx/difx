"""Step 3: render a run's findings as markdown pages in the DiFX wiki clone.

GitHub wiki page names form one flat namespace, so every page gets a unique name
(<prefix>-<component path with / -> ->, e.g. SA-libraries-difxio) while the
files are laid out like the source tree:

    <wiki>/<subdir>/Static-Analysis.md                 summary of all components
    <wiki>/<subdir>/libraries/SA-libraries-difxio.md   one page per component
    <wiki>/<subdir>/mpifxcorr/SA-mpifxcorr.md
    ...

Pages carry GENERATED_MARKER; on each render, marked pages that are no longer
produced are deleted, anything else in the directory is left alone.
"""

import json
import os
from collections import Counter

from . import compdb, components, diff
from .findings import SEVERITIES

GENERATED_MARKER = "<!-- generated by difx static-analysis/sa.py; do not edit -->"
CATEGORY_TITLES = {"libraries": "Libraries", "mpifxcorr": "mpifxcorr",
                   "applications": "Applications", "utilities": "Utilities"}
SEVERITY_ICON = {"error": "🔴", "warning": "🟠", "performance": "🔵",
                 "portability": "🟣", "style": "⚪"}


def log(msg):
    print(f"[render] {msg}", flush=True)


def esc(text):
    """Make text safe inside a markdown table cell."""
    text = " ".join(str(text).split())
    for a, b in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ("|", "\\|"),
                 ("[", "\\["), ("]", "\\]"), ("*", "\\*")):
        text = text.replace(a, b)
    return text


def severity_counts(items):
    c = Counter(f.severity for f in items)
    return [c.get(s, 0) for s in SEVERITIES]


def severity_summary(items):
    c = Counter(f.severity for f in items)
    return ", ".join(f"{c[s]} {s}" for s in SEVERITIES if c.get(s))


class Renderer:
    def __init__(self, cfg, rundir, run, prev_date):
        r = cfg.raw.get("report", {})
        self.prefix = r.get("page_prefix", "SA")
        self.source_url = r.get("source_url",
                                "https://github.com/difx/difx/blob/{sha}/{file}#L{line}")
        self.max_listed = r.get("max_listed", 300)
        self.trend_runs = r.get("trend_runs", 14)
        self.rundir = rundir
        self.run = run
        self.sha = run["checkout"]["sha"]
        self.prev_date = prev_date
        self.top = r.get("top_page", "Static-Analysis")

    # -- naming --------------------------------------------------------------
    def page_name(self, comp_path):
        return f"{self.prefix}-{comp_path.replace('/', '-')}"

    def page_file(self, comp_path):
        folder = os.path.dirname(comp_path) or comp_path
        return os.path.join(folder, self.page_name(comp_path) + ".md")

    def link(self, title, page):
        # not [[title|page]]: its "|" would split a table cell; wiki pages resolve
        # relative to /wiki/ whatever directory their file is in
        return f"[{title}]({page})"

    def src_link(self, f, text=None):
        url = self.source_url.format(sha=self.sha, file=f.file, line=f.line)
        return f"[{text or f.line}]({url})"

    # -- common pieces ------------------------------------------------------
    def run_line(self):
        co = self.run["checkout"]
        tools = ", ".join(f"{n} ({v})" for n, v in self.run["tools"].items())
        return (f"Branch **{co['branch']}** @ [`{co['sha'][:10]}`]"
                f"(https://github.com/difx/difx/commit/{co['sha']}) "
                f"({co['commit_date'][:10]}), analysed {self.run['date']}.  \n"
                f"Tools: {tools}.")

    def findings_table(self, items, new_keys=None, with_file=False):
        head = (["File"] if with_file else []) + ["Line", "Severity", "Tool", "Check", "Message"]
        rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
        for f in items[:self.max_listed]:
            mark = " 🆕" if new_keys is not None and id(f) in new_keys else ""
            cells = ([esc(f.file)] if with_file else []) + [
                self.src_link(f) + mark, f"{SEVERITY_ICON[f.severity]} {f.severity}",
                f.tool, f"`{f.check}`", esc(f.message)]
            rows.append("| " + " | ".join(cells) + " |")
        if len(items) > self.max_listed:
            rows.append(f"\n_… {len(items) - self.max_listed} more not shown._")
        return "\n".join(rows)

    # -- component page -----------------------------------------------------
    def component_page(self, comp, items, new, fixed):
        tools = list(self.run["tools"])
        out = [GENERATED_MARKER,
               f"# Static analysis: {comp['path']}", "",
               f"{self.link('Static Analysis', self.top)} › {comp['category']} › "
               f"**{os.path.basename(comp['path'])}**", "",
               self.run_line(), ""]

        # severity x tool counts
        by = Counter((f.severity, f.tool) for f in items)
        out += ["| Severity | " + " | ".join(tools) + " | Total |",
                "|---|" + "---:|" * (len(tools) + 1)]
        for s in SEVERITIES:
            row = [by.get((s, t), 0) for t in tools]
            if sum(row):
                out.append(f"| {SEVERITY_ICON[s]} {s} | " + " | ".join(map(str, row))
                           + f" | {sum(row)} |")
        tot = [sum(by.get((s, t), 0) for s in SEVERITIES) for t in tools]
        out.append("| **Total** | " + " | ".join(f"**{n}**" for n in tot)
                   + f" | **{sum(tot)}** |")
        f_ = comp["files"]
        out += ["", f"{f_['compiled']} compiled files, {f_['sources']} C/C++ sources and "
                f"headers, {f_['tracked']} tracked files analysed.", ""]

        # changes since the previous run
        if self.prev_date is None:
            out += ["## Changes", "", "First analysed run on this branch; nothing to compare.", ""]
        else:
            out += [f"## New since {self.prev_date} ({len(new)})", ""]
            out += [self.findings_table(new, with_file=True) if new else "None.", ""]
            out += [f"## Fixed since {self.prev_date} ({len(fixed)})", ""]
            if fixed:
                out += ["<details><summary>Show fixed findings</summary>", "",
                        self.findings_table(fixed, with_file=True), "", "</details>"]
            else:
                out.append("None.")
            out.append("")

        # by check
        checks = Counter((f.tool, f.check, f.severity) for f in items)
        out += ["## By check", "", "<details><summary>"
                f"{len(checks)} distinct checks</summary>", "",
                "| Tool | Check | Severity | Count |", "|---|---|---|---:|"]
        for (tool, check, sev), n in sorted(
                checks.items(), key=lambda kv: (SEVERITIES.index(kv[0][2]), -kv[1])):
            out.append(f"| {tool} | `{check}` | {SEVERITY_ICON[sev]} {sev} | {n} |")
        out += ["", "</details>", ""]

        # by file, most severe first
        new_ids = {id(f) for f in new}
        files = {}
        for f in items:
            files.setdefault(f.file, []).append(f)
        out += ["## By file", ""]
        for path in sorted(files, key=lambda p: [-n for n in severity_counts(files[p])] + [p]):
            group = sorted(files[path], key=lambda f: (f.line, f.column))
            n_new = sum(id(f) in new_ids for f in group)
            extra = f", {n_new} new" if n_new else ""
            out += [f"<details><summary><code>{esc(path)}</code> — "
                    f"{severity_summary(group)}{extra}</summary>", "",
                    self.findings_table(group, new_keys=new_ids), "", "</details>", ""]
        return "\n".join(out)

    # -- summary page -------------------------------------------------------
    def summary_page(self, rows, history, not_analysed):
        out = [GENERATED_MARKER, "# Static Analysis", "",
               "Daily results of the [static-analysis suite]"
               "(https://github.com/difx/difx/tree/dev/static-analysis) "
               "(clang-tidy, cppcheck, typos) over the DiFX components built by "
               "`install-difx`. Generated automatically; do not edit by hand.", "",
               self.run_line(), ""]
        cmp_ = f"since {self.prev_date}" if self.prev_date else "(first run)"
        head = ("| Component | Files | 🔴 Error | 🟠 Warning | 🔵 Perf. | 🟣 Port. | ⚪ Style "
                f"| Total | New {cmp_} | Fixed |")
        grand = [0] * 9
        for cat in components.CATEGORY_ORDER:
            cat_rows = [r for r in rows if r["category"] == cat]
            if not cat_rows:
                continue
            out += [f"## {CATEGORY_TITLES[cat]}", "", head, "|---|" + "---:|" * 9]
            for r in cat_rows:
                nums = [r["files"], *r["sev"], r["total"], r["new"], r["fixed"]]
                grand = [a + b for a, b in zip(grand, nums)]
                cells = [self.link(os.path.basename(r["path"]), self.page_name(r["path"]))] + [
                    str(n) if n else "" for n in nums]
                out.append("| " + " | ".join(cells) + " |")
            out.append("")
        out += ["## All components", "",
                f"**{grand[6]}** findings in {len(rows)} components: "
                + ", ".join(f"{n} {s}" for s, n in zip(SEVERITIES, grand[1:6]) if n)
                + (f"; {grand[7]} new and {grand[8]} fixed {cmp_}." if self.prev_date else "."),
                ""]

        out += ["## Trend", "", "| Date | Commit | Total | 🔴 Error | 🟠 Warning | New | Fixed |",
                "|---|---|---:|---:|---:|---:|---:|"]
        for h in reversed(history[-self.trend_runs:]):
            out.append(f"| {h['date']} | `{h['sha'][:10]}` | {h['total']} | {h['error']} | "
                       f"{h['warning']} | {h.get('new', '')} | {h.get('fixed', '')} |")
        out.append("")

        if not_analysed:
            out += ["## Not analysed", "", "| Component | Reason |", "|---|---|"]
            out += [f"| {p} | {esc(reason)} |" for p, reason in not_analysed]
            out.append("")
        return "\n".join(out)


def history(branchdir):
    """Per-run totals for the trend table, oldest first."""
    result = []
    for d in diff.run_dates(branchdir):
        try:
            with open(os.path.join(branchdir, d, "run.json")) as f:
                run = json.load(f)
        except FileNotFoundError:
            continue
        sev = Counter()
        for comp in run["components"].values():
            sev.update(comp.get("severity", {}))
        h = {"date": d, "sha": run["checkout"]["sha"],
             "total": sum(sum(c["counts"].values()) for c in run["components"].values()),
             "error": sev.get("error", 0), "warning": sev.get("warning", 0)}
        dfile = os.path.join(branchdir, d, "diff.json")
        if os.path.exists(dfile):
            with open(dfile) as f:
                dd = json.load(f)
            if dd.get("previous"):
                h["new"] = sum(c["new"] for c in dd["components"].values())
                h["fixed"] = sum(c["fixed"] for c in dd["components"].values())
        result.append(h)
    return result


def remove_stale(outdir, keep):
    for root, _, names in os.walk(outdir, topdown=False):
        for n in names:
            path = os.path.join(root, n)
            if n.endswith(".md") and path not in keep:
                with open(path) as f:
                    generated = f.readline().strip() == GENERATED_MARKER
                if generated:
                    os.remove(path)
                    log(f"removed stale {os.path.relpath(path, outdir)}")
        if root != outdir and not os.listdir(root):
            os.rmdir(root)


def write(path, text, written):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text.rstrip() + "\n")
    written.add(path)


def run(cfg, branch=None, date=None):
    branch = branch or compdb.read_checkout(cfg.workdir)["branch"]
    branchdir = cfg.results_dir(branch)
    dates = diff.run_dates(branchdir)
    if not dates:
        raise RuntimeError(f"no results for branch {branch} in {branchdir}")
    date = date or dates[-1]
    rundir = os.path.join(branchdir, date)
    with open(os.path.join(rundir, "run.json")) as f:
        run_info = json.load(f)
    prev = diff.previous_date(branchdir, date)
    prevdir = os.path.join(branchdir, prev) if prev else None

    outdir = cfg.wiki_dir
    r = Renderer(cfg, rundir, run_info, prev)
    log(f"{branch} {date} (previous: {prev or 'none'}) -> {outdir}")

    rows, diff_summary, written = [], {}, set()
    for name, comp in run_info["components"].items():
        items = diff.load_component(rundir, comp["path"]) or []
        before = diff.load_component(prevdir, comp["path"]) if prevdir else None
        new, fixed = diff.compare(items, before) if before is not None else ([], [])
        if prevdir and before is None:
            new = list(items)  # component analysed for the first time
        diff_summary[name] = {"new": len(new), "fixed": len(fixed)}
        comp["severity"] = dict(zip(SEVERITIES, severity_counts(items)))
        write(os.path.join(outdir, r.page_file(comp["path"])),
              r.component_page(comp, items, new, fixed), written)
        rows.append({"path": comp["path"], "category": comp["category"],
                     "files": comp["files"]["compiled"], "sev": severity_counts(items),
                     "total": len(items), "new": len(new), "fixed": len(fixed)})

    # keep severity totals in run.json for the trend table
    with open(os.path.join(rundir, "run.json"), "w") as f:
        json.dump(run_info, f, indent=1)
    with open(os.path.join(rundir, "diff.json"), "w") as f:
        json.dump({"previous": prev, "components": diff_summary}, f, indent=1)

    not_analysed = [(c.path, c.excluded) for c in
                    components.read_components(cfg.path("install_script"), cfg.excluded)
                    if c.enabled and c.excluded]
    order = {c: i for i, c in enumerate(components.CATEGORY_ORDER)}
    rows.sort(key=lambda x: (order[x["category"]], x["path"]))
    write(os.path.join(outdir, r.top + ".md"),
          r.summary_page(rows, history(branchdir), not_analysed), written)
    remove_stale(outdir, written)
    log(f"wrote {len(written)} pages")
    return 0
